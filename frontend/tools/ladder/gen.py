import random, collections, json
valid=sorted({w.strip() for w in open('enable1.txt') if len(w.strip())==4 and w.strip().isalpha()})
vs=set(valid)
# words unfit to show as a puzzle word (still accepted if typed, as any dictionary game does)
BAD=set("anal anus arse butt cock coon cunt damn dick dyke fags fuck gook hell homo jerk jism kike kill knob lust mick nazi piss poop porn pube rape scum sexy shag shit slag slut smut spic suck tits turd twat wank whop dead dies died gore guns hate hung drug rapt pimp boob dong fart puke crap bong weed cums dago wops tony josh matt nick gene char lang perl mens dans".split())
common=[w.strip() for w in open('common.txt')]
rank={w:i for i,w in enumerate(common)}
com=[w for w in common if len(w)==4 and w in vs and w not in BAD and rank[w]<7000]
# drop names/abbreviations that slipped into the frequency list but are in the dictionary only as rare words
cs=set(com)
def nbrs(w,pool):
    out=[]
    for i in range(4):
        for c in "abcdefghijklmnopqrstuvwxyz":
            if c!=w[i]:
                x=w[:i]+c+w[i+1:]
                if x in pool: out.append(x)
    return out
g={w:nbrs(w,cs) for w in com}
def bfs(s,pool_graph):
    d={s:0}; q=collections.deque([s])
    while q:
        u=q.popleft()
        for v in pool_graph[u]:
            if v not in d: d[v]=d[u]+1; q.append(v)
    return d
gv={w:nbrs(w,vs) for w in valid}
random.seed(20261124)
puz=collections.defaultdict(list)
starts=[w for w in com if len(g[w])>=3 and rank[w]<4000]
random.shuffle(starts)
for s in starts:
    d=bfs(s,g)
    for t,k in d.items():
        if 2<=k<=6 and rank[t]<4000 and len(g[t])>=2:
            diff=sum(a!=b for a,b in zip(s,t))
            if diff<2: continue            # one letter apart is not a puzzle
            if len(set(s)&set(t))>=4: continue
            puz[k].append((s,t))
out=[]
want={2:70,3:120,4:120,5:80,6:40}
used=collections.Counter()
for k,n in want.items():
    random.shuffle(puz[k]); c=0
    for s,t in puz[k]:
        if used[s]>=(2 if k<5 else 5) or used[t]>=(2 if k<5 else 5): continue
        used[s]+=1; used[t]+=1; out.append([s,t,k]); c+=1
        if c>=n: break
    print(k,"available",len(puz[k]),"kept",c)
print("valid",len(valid),"common",len(com),"puzzles",len(out)); print(out[:6], out[200:204], out[-4:])
ts='''// Generated by tools/ladder/gen.py. Do not edit by hand.
// VALID: every four-letter word the game accepts (ENABLE word list, public domain).
// PUZZLES: [start, target, par]. Both words and one shortest route use everyday
// words only; par is the length of that route.
export const VALID = "%s";
export const PUZZLES: [string, string, number][] = %s;
''' % (" ".join(valid), json.dumps(out,separators=(",",":")))
open('data.ts','w').write(ts); print(len(ts),"bytes")
